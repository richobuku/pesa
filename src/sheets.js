  /**
   * Find the first safe empty row on `Spending` (scanning yellow input columns from row 5 down).
   * A row is considered empty only when Date (B), Category (C), Description (F), and Amount (J) are all empty.
   */
  async findNextEmptySpendingRow(maxRow = 1504) {
    const rows = await this.getRangeValues(`Spending!B5:K${maxRow}`, 'UNFORMATTED_VALUE');
    for (let i = 0; i < maxRow - 4; i++) {
      const r = rows[i] || [];
      const bDate = r[0];
      const cCat = r[1];
      const fDesc = r[4];
      const jAmt = r[8];
      const isEmpty =
        (bDate === undefined || String(bDate).trim() === '') &&
        (cCat === undefined || String(cCat).trim() === '') &&
        (fDesc === undefined || String(fDesc).trim() === '') &&
        (jAmt === undefined || String(jAmt).trim() === '' || Number(jAmt) === 0);
      if (isEmpty) {
        return i + 5;
      }
    }
    return rows.length + 5;
  }

